const { chromium } = require("playwright");
const assert = require("node:assert/strict");
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || "/usr/bin/chromium", args: ["--no-sandbox"] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1080 } });
  const errors = [];
  page.on("pageerror", (e) => errors.push(e.message));
  await page.goto(process.env.BASE_URL || "http://127.0.0.1:8000");
  await page.waitForSelector(".task-row");
  const row = (title) => page.locator(".task-row").filter({ has: page.getByRole("button", { name: title, exact: true }) });
  const save = async () => {
    await page.locator("#task-form button[type=submit]").click();
    await page.waitForSelector("#task-dialog", { state: "hidden" });
  };
  const parent = "整理首頁設計靈感";
  await row(parent).locator("[data-add-child]").click();
  assert.notEqual(await page.locator("[name=parent_task_id]").inputValue(), "");
  await page.locator("#task-form [name=title]").fill("階層子任務");
  await page.locator("#task-form [name=priority]").selectOption("low");
  await page.locator("#task-form [name=planned_date]").fill("2026-12-01");
  await save();
  assert.match(await row("階層子任務").innerText(), /上層：整理首頁設計靈感/);
  assert.match(await row(parent).innerText(), /子任務 0 \/ 1 完成/);
  await row("階層子任務").locator("[data-add-child]").click();
  await page.locator("#task-form [name=title]").fill("階層孫任務");
  await save();
  await row(parent).locator(".title-button").click();
  assert.equal(await page.locator("[name=parent_task_id] option").filter({ hasText: "階層" }).count(), 0);
  await page.locator("[data-close=task-dialog]").first().click();
  await row(parent).locator("[data-toggle]").click();
  assert.equal(await row("階層子任務").count(), 0);
  await page.locator("#search").fill("階層");
  assert.equal(await page.locator(".task-row").count(), 2);
  // Matching parents must expose their actual expanded state during filtering.
  await page.locator("#search").fill("階層子任務");
  await page.locator("#priority-filter").selectOption("low");
  await page.locator("#search").fill("");
  assert.equal(await row("階層子任務").locator("[data-toggle]").getAttribute("aria-expanded"), "true");
  assert.equal(await row("階層子任務").locator("[data-toggle]").isDisabled(), true);
  await page.locator("#priority-filter").selectOption("");
  await row(parent).locator("[data-toggle]").click();
  await row(parent).locator("[data-complete]").check();
  assert.equal(await row("階層子任務").locator("[data-complete]").isChecked(), false);
  await row("階層子任務").locator("[data-complete]").check();
  await page.waitForFunction(() => [...document.querySelectorAll('.child-progress')].some((e) => e.textContent === '子任務 1 / 1 完成'));
  await row("階層子任務").locator(".title-button").click();
  assert.equal(await page.locator("[name=planned_date]").inputValue(), "2026-12-01");
  assert.equal(await page.locator("#task-form [name=priority]").inputValue(), "low");
  await page.locator("[name=parent_task_id]").selectOption({ label: "畫下自己的小點子" });
  await save();
  assert.match(await row("階層子任務").innerText(), /上層：畫下自己的小點子/);
  await row("階層子任務").locator(".title-button").click();
  await page.locator("[name=parent_task_id]").selectOption("");
  await save();
  assert.equal(await row("階層子任務").locator(".parent-path").count(), 0);
  page.once("dialog", async (d) => { assert.match(d.message(), /改為獨立任務/); await d.dismiss(); });
  await row("階層子任務").locator("[data-delete]").click();
  assert.equal(await row("階層孫任務").count(), 1);
  page.once("dialog", (d) => d.accept());
  await row("階層子任務").locator("[data-delete]").click();
  await row("階層子任務").waitFor({ state: "detached" });
  assert.equal(await row("階層孫任務").locator(".parent-path").count(), 0);
  await page.evaluate(() => document.fonts.ready);
  assert.ok(await page.evaluate(() => document.fonts.check('14px "Montserrat"') && document.fonts.check('14px "jf open 粉圓"')));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator("#mobile-theme").selectOption("cozy");
  await row("階層孫任務").locator("[data-add-child]").click();
  await page.locator("#task-form [name=title]").fill("手機子任務與很長很長很長很長的名稱");
  await save();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: "/tmp/julia-hierarchy-mobile.png", fullPage: true });
  assert.deepEqual(errors, []);
  await browser.close();
  console.log("PASS: hierarchy creation, cycle-safe choices, collapse, search, independent completion, progress, reparent/detach, deletion cancel/preserve, local fonts and mobile.");
})().catch((error) => { console.error(error); process.exit(1); });
